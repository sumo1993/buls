-- Migration: Add 'collected' status to payment workflow
-- This creates proper separation between Treasurer (collection) and Finance (approval)

-- Step 1: Add 'collected' to payment_status enum
-- Note: PostgreSQL doesn't support IF NOT EXISTS for ADD VALUE, so we need to check manually
-- Run this in Supabase SQL Editor:

DO $$
BEGIN
    -- Check if 'collected' exists in the enum
    IF NOT EXISTS (SELECT 1 FROM pg_enum WHERE enumlabel = 'collected' AND enumtypid = (SELECT oid FROM pg_type WHERE typname = 'payment_status')) THEN
        -- Add 'collected' status
        ALTER TYPE payment_status ADD VALUE 'collected' AFTER 'pending';
    END IF;
END
$$;

-- Step 2: Add collection tracking fields to payments table
ALTER TABLE payments 
ADD COLUMN IF NOT EXISTS collected_by UUID REFERENCES users(id),
ADD COLUMN IF NOT EXISTS collected_at TIMESTAMP WITH TIME ZONE,
ADD COLUMN IF NOT EXISTS collection_method TEXT,
ADD COLUMN IF NOT EXISTS collection_notes TEXT;

-- Step 3: Add index for collection queries
CREATE INDEX IF NOT EXISTS idx_payments_collected_by ON payments(collected_by);

-- Step 4: Add receipt/record tracking for Finance
ALTER TABLE payments 
ADD COLUMN IF NOT EXISTS receipt_number TEXT,
ADD COLUMN IF NOT EXISTS recorded_by UUID REFERENCES users(id),
ADD COLUMN IF NOT EXISTS recorded_at TIMESTAMP WITH TIME ZONE;

-- Create index for receipt lookups
CREATE INDEX IF NOT EXISTS idx_payments_receipt_number ON payments(receipt_number);

-- Step 5: Add function to generate receipt numbers
CREATE OR REPLACE FUNCTION generate_receipt_number(p_year INTEGER)
RETURNS TEXT AS $$
DECLARE
  sequence_num TEXT;
  new_receipt_number TEXT;
BEGIN
  -- Get sequence number for this year
  SELECT LPAD((COUNT(*) + 1)::TEXT, 5, '0')
  INTO sequence_num
  FROM payments
  WHERE year = p_year AND status = 'approved';
  
  new_receipt_number := 'REC-' || p_year || '-' || sequence_num;
  
  RETURN new_receipt_number;
END;
$$ LANGUAGE plpgsql;

-- Step 6: Create financial_reports table for Finance reports
CREATE TABLE IF NOT EXISTS financial_reports (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  report_type TEXT NOT NULL, -- 'monthly', 'quarterly', 'annual', 'custom'
  report_period TEXT NOT NULL, -- '2024-01', '2024-Q1', '2024', or custom range
  generated_by UUID REFERENCES users(id),
  generated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  total_revenue DECIMAL(10, 2),
  total_payments INTEGER,
  total_loans_issued DECIMAL(10, 2),
  total_loans_repaid DECIMAL(10, 2),
  report_data JSONB, -- Stores detailed report data
  notes TEXT,
  submitted_to_body BOOLEAN DEFAULT FALSE,
  submitted_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_financial_reports_type ON financial_reports(report_type);
CREATE INDEX IF NOT EXISTS idx_financial_reports_period ON financial_reports(report_period);

